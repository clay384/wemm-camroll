"""Read-only ancestry for an explicitly authorized, independent Gate continuation.

No request is replayed here. Stored turns are measurements; only subsequent
turns may be generated by the new run, with the original conversation history.
"""
from __future__ import annotations

import copy
from pathlib import Path
import shutil
import sqlite3

from .common import read_json, sha256, safe_id
from .dataset import Dataset


def validate_history(history):
    if not isinstance(history, list) or not history:
        raise ValueError("Continuation requires a persisted conversation")
    pending, seen = set(), set()
    for message in history:
        if not isinstance(message, dict) or message.get("role") not in {"user", "assistant", "tool"}:
            raise ValueError("Unexpected persisted conversation role")
        if message["role"] == "assistant":
            if pending:
                raise ValueError("Unresolved tools in persisted conversation")
            for call in message.get("tool_calls") or []:
                identifier = call.get("id")
                if not isinstance(identifier, str) or not identifier or identifier in seen:
                    raise ValueError("Invalid persisted tool identity")
                seen.add(identifier)
                pending.add(identifier)
        elif message["role"] == "tool":
            if message.get("tool_call_id") not in pending:
                raise ValueError("Unmatched persisted tool result")
            pending.remove(message["tool_call_id"])
        elif pending:
            raise ValueError("User turn precedes pending tool results")
    if pending or history[-1].get("role") != "assistant":
        raise ValueError("Persisted conversation has unfinished operations")


class ContinuationParent:
    def __init__(self, specification, *, state, dataset, binding, acknowledged_call_ids):
        from .gate_experiment import valid_judgment
        if not isinstance(specification, dict) or set(specification) != {"path", "sha256"}:
            raise ValueError("Continuation requires an exact parent path and SHA256")
        self.path = Path(specification["path"]).resolve()
        self.digest = specification["sha256"]
        if self.path.name != "run.json" or sha256(self.path) != self.digest:
            raise ValueError("Continuation parent hash mismatch")
        parent = read_json(self.path)
        if (parent.get("mode") != "gate_ab" or parent.get("status") != "blocked"
                or parent.get("stop_reason") != "request_uncertain"
                or parent.get("source_unchanged") is not True or parent.get("finalization_errors")
                or parent.get("run_id") == state["run_id"] or parent.get("suite_id") == state["suite_id"]):
            raise ValueError("Continuation requires the stopped, immutable source run")
        for field in ("inference_config", "inference_fingerprint", "input_integrity", "index_binding",
                      "index_binding_fingerprint", "qa_plan", "album_id", "index_version"):
            if parent.get(field) != state.get(field):
                raise ValueError("Continuation parent differs in " + field)
        journal = self.path.parent / "request-journal.sqlite"
        if not journal.is_file() or not acknowledged_call_ids:
            raise ValueError("Continuation requires acknowledged uncertain request identities")
        with sqlite3.connect(journal.as_uri() + "?mode=ro", uri=True) as connection:
            uncertain = {row[0] for row in connection.execute("SELECT call_id FROM cloud_requests WHERE status='uncertain'")}
        if uncertain != set(acknowledged_call_ids):
            raise ValueError("Continuation does not acknowledge exactly the parent's uncertain requests")
        items = parent.get("items") or []
        if not items or len(items) > len(dataset.rows):
            raise ValueError("Continuation source has no valid executed prefix")
        if [row["qa_id"] for row in items] != [row["qa_id"] for row in dataset.rows[:len(items)]]:
            raise ValueError("Continuation source questions are not a contiguous prefix")
        self.items, self.artifacts, preserved = {}, {}, []
        self.destination = None
        for position, (original, definition) in enumerate(zip(items, dataset.rows)):
            turns, definitions = original.get("runtime_turns") or [], Dataset.turns(definition)
            if not turns or len(turns) > len(definitions) or [turn.get("index") for turn in turns] != list(range(len(turns))):
                raise ValueError("Continuation source turns are not a contiguous prefix")
            if position < len(items) - 1 and len(turns) != len(definitions):
                raise ValueError("Only the last source question may be incomplete")
            item = copy.deepcopy(original)
            for turn, expected in zip(item["runtime_turns"], definitions):
                if turn.get("message") != expected["message"] or turn.get("expected_action") != expected["expected_action"]:
                    raise ValueError("Persisted turn differs from frozen input")
                if turn.get("judge_eligible"):
                    if not valid_judgment(turn) or turn.get("judge_status") != "completed":
                        raise ValueError("Continuation cannot silently replace missing prior scores")
                elif turn.get("judge_status") != "skipped_expected" or (turn.get("judge") or {}).get("score") is not None:
                    raise ValueError("Invalid failure scoring in source run")
                relative = Path(turn.get("raw_attempt_path", ""))
                raw_path = (self.path.parent / relative).resolve()
                if relative.is_absolute() or not relative.parts or self.path.parent not in raw_path.parents or not raw_path.is_file():
                    raise ValueError("Continuation raw attempt is unavailable")
                raw = read_json(raw_path)
                if (raw.get("context", {}).get("qa_id") != item["qa_id"]
                        or raw.get("context", {}).get("turn_index") != turn["index"]):
                    raise ValueError("Continuation raw attempt identity mismatch")
                target = Path("inherited_turn_attempts") / safe_id(item["qa_id"]) / (str(turn["index"]) + ".json")
                self.artifacts[str(target)] = (raw_path, sha256(raw_path))
                turn["raw_attempt_path"] = str(target)
                turn["record_provenance"] = {"kind": "inherited", "run_id": parent["run_id"],
                    "run_sha256": self.digest, "turn_index": turn["index"], "original_raw_attempt_path": str(relative)}
                preserved.append({"qa_id": item["qa_id"], "turn_index": turn["index"]})
            if len(turns) < len(definitions):
                validate_history(item.get("conversation_history"))
                last_raw = read_json(self.artifacts[str(Path("inherited_turn_attempts") / safe_id(item["qa_id"]) / (str(turns[-1]["index"]) + ".json"))][0])
                if item["conversation_history"] != last_raw.get("response", {}).get("conversation_history"):
                    raise ValueError("Continuation history differs from the persisted response")
            item["record_provenance"] = {"kind": "inherited", "run_id": parent["run_id"], "run_sha256": self.digest}
            self.items[item["qa_id"]] = item
        self.metadata = {"schema_version": "camroll-gate-continuation-v1", "parent_run_id": parent["run_id"],
            "parent_run_path": str(self.path), "parent_run_sha256": self.digest, "source_suite_id": parent["suite_id"],
            "preserved_turns": preserved, "inherited_turn_count": len(preserved),
            "new_turn_count": state["planned_turn_count"] - len(preserved),
            "acknowledged_call_ids": sorted(acknowledged_call_ids), "unknown_request_policy": "preserve_reservation_skip_request",
            "prior_failures_preserved": True, "prior_scores_preserved": True,
            "source_records_unchanged": True, "completed_requests_resent": False,
            "history_restored_only_within_question": True}

    def materialize(self, destination):
        self.destination = Path(destination).resolve()
        for relative, (source, digest) in self.artifacts.items():
            target = Path(destination) / relative
            target.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
            if target.exists() or sha256(source) != digest:
                raise ValueError("Inherited raw attempt changed or destination exists")
            shutil.copyfile(source, target)
            target.chmod(0o600)
            if sha256(target) != digest:
                raise ValueError("Inherited raw attempt copy mismatch")
        self.validate()

    def validate(self):
        if sha256(self.path) != self.digest or any(sha256(source) != digest for source, digest in self.artifacts.values()):
            raise ValueError("Continuation source changed")
        if self.destination is not None:
            for relative, (_, digest) in self.artifacts.items():
                target = self.destination / relative
                if (target.resolve() != target or not target.is_file() or target.is_symlink()
                        or sha256(target) != digest):
                    raise ValueError("Inherited raw attempt copy changed")
